/** Punctuation stays outside the bold: "**שתו מים**, בלי להתבייש." */
const punctuationOut = (marked) => marked.replace(/([,.:!?]+)\*\*/g, '**$1');

/**
 * The rule for a list item: the part before the colon, else the first clause
 * (up to a comma or a full stop) when it's short. Anything else needs an entry
 * in MARKED, and is left unmarked (and reported) until it has one.
 */
function emphasise(text, unmarked) {
  if (MARKED[text]) return MARKED[text];
  const colon = text.indexOf(': ');
  if (colon > 0 && text.slice(0, colon).split(' ').length <= MAX_WORDS) {
    return `**${text.slice(0, colon + 1)}**${text.slice(colon + 1)}`;
  }
  const clause = text.match(/^([^,.(?!]+[,.!?]?)/);
  if (clause && clause[1].trim().split(' ').length <= MAX_WORDS && !/^(אם|כש|גם|זה|לא) /.test(text)) {
    return `**${clause[1]}**${text.slice(clause[1].length)}`;
  }
  unmarked.push(text);
  return text;
}

